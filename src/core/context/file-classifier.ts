export type FileCategory =
  | 'source'
  | 'test'
  | 'documentation'
  | 'config'
  | 'lockfile'
  | 'generated'
  | 'binary'
  | 'asset'
  | 'other';

export interface FileClassification {
  readonly category: FileCategory;
  /** Whether the content carries change intent worth reporting. */
  readonly important: boolean;
  readonly reason?: string;
}

export interface ClassifiableFile {
  readonly path: string;
  readonly isBinary: boolean;
  readonly hunks: readonly { readonly lines: readonly string[] }[];
}

const LOCKFILES = new Set([
  'package-lock.json',
  'npm-shrinkwrap.json',
  'pnpm-lock.yaml',
  'yarn.lock',
  'bun.lockb',
  'cargo.lock',
  'poetry.lock',
  'pipfile.lock',
  'composer.lock',
  'gemfile.lock',
  'go.sum',
  'deno.lock',
  'mix.lock',
  'podfile.lock',
  'packages.lock.json',
]);

const LOCKFILE_PATTERN = /(^|\/)(.*\.lock|.*-lock\.json)$/i;

const GENERATED_SEGMENTS = [
  'node_modules/',
  'dist/',
  'build/',
  'out/',
  'vendor/',
  'coverage/',
  '.next/',
  '.nuxt/',
  '__generated__/',
  'generated/',
];

const GENERATED_SUFFIXES = ['.min.js', '.min.css', '.map', '.snap', '.generated.ts', '.generated.js', '.g.ts', '.g.dart'];

const ASSET_EXTENSIONS = [
  '.png',
  '.jpg',
  '.jpeg',
  '.gif',
  '.webp',
  '.ico',
  '.bmp',
  '.svg',
  '.pdf',
  '.woff',
  '.woff2',
  '.ttf',
  '.eot',
  '.mp4',
  '.webm',
  '.mp3',
  '.wav',
  '.zip',
  '.gz',
  '.tar',
];

const TEST_PATTERN = /(^|\/)(__tests__|tests?|spec|e2e)\/|\.(test|spec|e2e)\.[a-z0-9]+$/i;
const DOC_PATTERN = /\.(md|mdx|rst|adoc|txt)$/i;
const CONFIG_PATTERN =
  /(^|\/)(package\.json|tsconfig[^/]*\.json|jsconfig[^/]*\.json|\.gitignore|\.editorconfig|\.eslintrc[^/]*|\.prettierrc[^/]*|dockerfile|makefile|[^/]*\.config\.(js|mjs|cjs|ts))$/i;
const CONFIG_EXTENSION = /\.(json|ya?ml|toml|ini|properties|xml)$/i;
const SOURCE_EXTENSION =
  /\.(ts|tsx|mts|cts|js|jsx|mjs|cjs|py|go|rs|java|kt|kts|cs|cpp|cc|c|h|hpp|rb|php|swift|scala|sh|ps1|sql|vue|svelte|astro|lua|dart|ex|exs|erl|clj|hs|ml|nim|zig|proto|graphql|gql)$/i;

const GENERATED_MARKERS = [
  '@generated',
  'do not edit',
  'auto-generated',
  'automatically generated',
  'generated by',
  'this file is generated',
];

function baseName(path: string): string {
  const parts = path.split('/');
  return (parts[parts.length - 1] ?? '').toLowerCase();
}

function hasGeneratedMarker(file: ClassifiableFile): boolean {
  const lines = file.hunks.flatMap((hunk) => hunk.lines).slice(0, 20);
  for (const line of lines) {
    const lower = line.toLowerCase();
    if (GENERATED_MARKERS.some((marker) => lower.includes(marker))) {
      return true;
    }
  }
  return false;
}

export function classifyPath(path: string): FileClassification {
  const normalized = path.replace(/\\/g, '/').toLowerCase();
  const name = baseName(normalized);

  if (LOCKFILES.has(name) || LOCKFILE_PATTERN.test(normalized)) {
    return { category: 'lockfile', important: false, reason: 'lockfile' };
  }
  if (GENERATED_SEGMENTS.some((segment) => normalized.includes(segment))) {
    return { category: 'generated', important: false, reason: 'generated directory' };
  }
  if (GENERATED_SUFFIXES.some((suffix) => normalized.endsWith(suffix))) {
    return { category: 'generated', important: false, reason: 'generated artifact' };
  }
  if (ASSET_EXTENSIONS.some((extension) => normalized.endsWith(extension))) {
    return { category: 'asset', important: false, reason: 'binary asset' };
  }
  if (TEST_PATTERN.test(normalized)) {
    return { category: 'test', important: true };
  }
  if (DOC_PATTERN.test(normalized)) {
    return { category: 'documentation', important: true };
  }
  if (CONFIG_PATTERN.test(normalized) || CONFIG_EXTENSION.test(normalized)) {
    return { category: 'config', important: true };
  }
  if (SOURCE_EXTENSION.test(normalized)) {
    return { category: 'source', important: true };
  }
  return { category: 'other', important: true };
}

export function classifyFile(file: ClassifiableFile): FileClassification {
  if (file.isBinary) {
    return { category: 'binary', important: false, reason: 'binary content' };
  }
  if (hasGeneratedMarker(file)) {
    return { category: 'generated', important: false, reason: 'generated marker' };
  }
  return classifyPath(file.path);
}
