import { describe, expect, it } from 'vitest';
import { classifyFile, classifyPath } from '../../../src/core/context/file-classifier.js';

function file(path: string, options: { binary?: boolean; lines?: string[] } = {}) {
  return {
    path,
    isBinary: options.binary ?? false,
    hunks: [{ lines: options.lines ?? [] }],
  };
}

describe('classifyFile', () => {
  it('classifies source files as important', () => {
    const result = classifyFile(file('src/git/collector.ts'));
    expect(result.category).toBe('source');
    expect(result.important).toBe(true);
  });

  it('classifies tests, docs and configuration', () => {
    expect(classifyFile(file('src/git/collector.test.ts')).category).toBe('test');
    expect(classifyFile(file('docs/guide.md')).category).toBe('documentation');
    expect(classifyFile(file('package.json')).category).toBe('config');
  });

  it('detects lockfiles', () => {
    expect(classifyFile(file('package-lock.json')).category).toBe('lockfile');
    expect(classifyFile(file('pnpm-lock.yaml')).category).toBe('lockfile');
    expect(classifyFile(file('go.sum')).category).toBe('lockfile');
    expect(classifyFile(file('modules/feature/yarn.lock')).category).toBe('lockfile');
    expect(classifyFile(file('package-lock.json')).important).toBe(false);
  });

  it('detects generated directories and artifacts', () => {
    expect(classifyFile(file('dist/extension.js')).category).toBe('generated');
    expect(classifyFile(file('packages/a/vendor/lib.js')).category).toBe('generated');
    expect(classifyFile(file('src/bundle.min.js')).category).toBe('generated');
    expect(classifyFile(file('src/schema.generated.ts')).category).toBe('generated');
  });

  it('detects generated markers in content', () => {
    const result = classifyFile(
      file('src/api.ts', { lines: ['+// Code generated by protoc. DO NOT EDIT.', '+export const x = 1;'] }),
    );
    expect(result.category).toBe('generated');
    expect(result.important).toBe(false);
  });

  it('flags binary files', () => {
    const result = classifyFile(file('assets/logo.bin', { binary: true }));
    expect(result.category).toBe('binary');
    expect(result.important).toBe(false);
  });

  it('classifies assets', () => {
    expect(classifyFile(file('media/icon.png')).category).toBe('asset');
  });

  it('treats unknown text files as important', () => {
    const result = classifyFile(file('LICENSE'));
    expect(result.category).toBe('other');
    expect(result.important).toBe(true);
  });

  it('classifies by path alone for omitted files', () => {
    expect(classifyPath('src/app.ts').important).toBe(true);
    expect(classifyPath('yarn.lock').important).toBe(false);
  });
});
